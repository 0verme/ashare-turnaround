"""Lossless normalized replay artifacts and deterministic audit helpers.

The scanner's feature and score contracts deliberately remain unchanged in this
module.  It only changes how a completed logical payload is represented on
 disk: immutable JSON subtrees are put in a snapshot-local content-addressed
store and evidence records retain explicit references to those subtrees.

The logical/physical boundary is intentional:

* ``FeatureVector.as_dict()`` and ``ReplayResult.artifact_dict()`` are the
  semantic, expanded contracts;
* ``pit-replay-artifact-normalized-v1`` is a physical layout contract;
* expansion is required to be lossless, including every evidence and audit
  field.  Deduplication is never a permission to drop evidence.
"""

