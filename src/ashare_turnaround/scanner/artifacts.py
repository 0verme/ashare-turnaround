def _json_safe(value: Any, _memo: dict[int, Any] | None = None) -> Any:
    """Convert common pandas/numpy values to finite JSON-compatible values."""

    memo = _memo if _memo is not None else {}
    if value is None or value is pd.NA or value is pd.NaT:
        return None
    if isinstance(value, (pd.Timestamp, datetime, date)):
        timestamp = pd.Timestamp(value)
        if timestamp.tzinfo is not None:
            timestamp = timestamp.tz_localize(None)
        return timestamp.isoformat()
    if isinstance(value, Mapping):
        object_key = id(value)
        if object_key in memo:
            return memo[object_key]
        result: dict[str, Any] = {}
        memo[object_key] = result
        result.update({str(key): _json_safe(item, memo) for key, item in value.items()})
        return result
    if isinstance(value, (list, tuple)):
        object_key = id(value)
        if object_key in memo:
            return memo[object_key]
        result_list: list[Any] = []
        memo[object_key] = result_list
        result_list.extend(_json_safe(item, memo) for item in value)
        return result_list
    if isinstance(value, (set, frozenset)):
        values = [_json_safe(item, memo) for item in value]
        return sorted(values, key=lambda item: canonical_json_bytes(item))
    if isinstance(value, bool):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if hasattr(value, "item") and not isinstance(value, (str, bytes)):
        try:
            return _json_safe(value.item(), memo)
        except (TypeError, ValueError, OverflowError):
            pass
    if hasattr(value, "tolist") and not isinstance(value, (str, bytes)):
        try:
            return _json_safe(value.tolist(), memo)
        except (TypeError, ValueError):
            pass
    try:
        missing = pd.isna(value)
        if isinstance(missing, bool) and missing:
            return None
    except (TypeError, ValueError):
        pass
    return value


def _canonical_safe_bytes(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")


def canonical_json_bytes(value: Any) -> bytes:
    """Return the canonical UTF-8 JSON bytes used by every content hash."""

    return _canonical_safe_bytes(_json_safe(value))


def canonical_json(value: Any) -> str:
    return canonical_json_bytes(value).decode("utf-8")


def content_digest(value: Any) -> str:
    """Return a full SHA-256 hex digest over canonical JSON."""

    return hashlib.sha256(canonical_json_bytes(value)).hexdigest()


def content_ref(value: Any) -> str:
    """Return the canonical content-address format used in normalized files."""

    return _REF_PREFIX + content_digest(value)


def _mapping_content_digest(value: Mapping[str, Any]) -> str:
    """Hash a large mapping in bounded memory while preserving JSON ordering."""

    digest = hashlib.sha256()
    digest.update(b"{")
    for index, key in enumerate(sorted(value, key=str)):
        if index:
            digest.update(b",")
        digest.update(_canonical_safe_bytes(str(key)))
        digest.update(b":")
        child = value[key]
        digest.update(
            _physical_store_value_bytes(child)
            if isinstance(child, bytes)
            else canonical_json_bytes(child)
        )
    digest.update(b"}")
    return digest.hexdigest()


def serialized_json_bytes(value: Any) -> bytes:
    """Return deterministic bytes matching the pretty JSON artifact writer."""

    return (
        json.dumps(
            _json_safe(value),
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
        + "\n"
    ).encode("utf-8")


def _is_container(value: Any) -> bool:
    return isinstance(value, (Mapping, list, tuple))


def _store_bytes(value: Any) -> bytes:
    """Encode one node without defeating cross-node stream compression.

    Earlier artifacts compressed every node independently at zlib level 9 and
    then base64 encoded it.  Besides being CPU intensive, that hid repetition
    between neighbouring nodes from the final compressor.  The decoder still
    accepts that legacy representation, but newly built stores retain canonical
    plain JSON bytes and are compressed once by the snapshot writer.
    """

    return _canonical_safe_bytes(value)


def _is_compressed_bytes(value: Any) -> bool:
    return isinstance(value, bytes) and value.startswith(_COMPRESSED_PREFIX)


def _compressed_wrapper(value: bytes) -> dict[str, str]:
    return {
        "encoding": _COMPRESSED_ENCODING,
        "data": value[len(_COMPRESSED_PREFIX) :].decode("ascii"),
    }


def _is_compressed_wrapper(value: Any) -> bool:
    return (
        isinstance(value, Mapping)
        and value.get("encoding") == _COMPRESSED_ENCODING
        and isinstance(value.get("data"), str)
    )


def _decode_store_bytes(value: bytes) -> Any:
    raw = (
        zlib.decompress(base64.b64decode(value[len(_COMPRESSED_PREFIX) :]))
        if _is_compressed_bytes(value)
        else value
    )
    return json.loads(raw.decode("utf-8"))


def _decode_store_value(value: Any) -> Any:
    if _is_compressed_bytes(value):
        return _decode_store_bytes(value)
    if _is_compressed_wrapper(value):
        compressed = _COMPRESSED_PREFIX + value["data"].encode("ascii")
        return _decode_store_bytes(compressed)
    return copy.deepcopy(value)


def _physical_store_value_bytes(value: Any) -> bytes:
    if isinstance(value, bytes):
        return (
            _canonical_safe_bytes(_compressed_wrapper(value))
            if _is_compressed_bytes(value)
            else value
        )
    return canonical_json_bytes(value)


class ContentAddressedStore:
    """Snapshot-local Merkle-style store keyed by logical JSON content.

    Hashes are computed from the original logical subtree.  Store entries may
    contain references to child entries; this makes repeated nested objects
    (for example TrendSummary observations) physically unique as well as
    repeated top-level provenance objects.
    """

    def __init__(self, entries: Mapping[str, Any] | None = None) -> None:
        # Encoded nodes are kept as canonical JSON bytes in memory.  Parsed
        # Python trees multiply the resident set dramatically for a 100-stock
        # stream even when the final JSON is only a few hundred MiB.
        self._entries: dict[str, bytes] = {}
        self._physical_bytes = 0
        # This cache is intentionally scoped by normalize_feature_vector;
        # retaining source objects across streamed candidates would defeat the
        # memory benefit of the physical store.
        self._identity_cache: dict[int, tuple[Any, str]] = {}
        # Share JSON-safe conversions across aliased nested provenance within
        # one candidate.  TrendSummary deliberately reuses observations and
        # source chains across component evidence records.
        self._safe_cache: dict[int, Any] = {}
        if entries is not None:
            for key, value in entries.items():
                ref = str(key)
                if not ref.startswith(_REF_PREFIX):
                    raise ValueError(f"invalid content-addressed ref: {ref!r}")
                if isinstance(value, bytes):
                    encoded = bytes(value)
                elif _is_compressed_wrapper(value):
                    encoded = _COMPRESSED_PREFIX + value["data"].encode("ascii")
                else:
                    encoded = _store_bytes(_json_safe(value))
                self._entries[ref] = encoded
                self._physical_bytes += len(encoded)

    @property
    def entries(self) -> dict[str, Any]:
        return {
            key: _decode_store_bytes(value)
            for key, value in sorted(self._entries.items())
        }

    @property
    def physical_entries(self) -> dict[str, Any]:
        """Return JSON-native physical store values for an artifact payload."""

        return {
            key: (
                _compressed_wrapper(value)
                if _is_compressed_bytes(value)
                else _decode_store_bytes(value)
            )
            for key, value in sorted(self._entries.items())
        }

    def iter_entries_sorted(self) -> Iterator[tuple[str, bytes]]:
        """Yield physical entries in ref order without a second dictionary."""

        for key in sorted(self._entries):
            yield key, self._entries[key]

    def entries_view(self) -> Mapping[str, bytes]:
        """Compatibility view for small stores only.

        Production streaming paths use :meth:`iter_entries_sorted`; this
        method intentionally remains a materialising compatibility API.
        """

        return dict(self.iter_entries_sorted())

    @property
    def entry_count(self) -> int:
        return len(self._entries)

    @property
    def physical_byte_count(self) -> int:
        return self._physical_bytes

    def __len__(self) -> int:
        return len(self._entries)

    def clear_identity_cache(self) -> None:
        self._identity_cache.clear()
        self._safe_cache.clear()

    clear_candidate_identity_cache = clear_identity_cache

    def _encode_child(self, value: Any) -> Any:
        if _is_container(value):
            return {_REF_KEY: self._intern_safe(value)}
        return value

    def _encode_node(self, value: Any) -> Any:
        if isinstance(value, Mapping):
            return {
                str(key): (
                    self._encode_child(child)
                    if str(key) in _ARTIFACT_AWARE_CAS_KEYS
                    else child
                )
                for key, child in value.items()
            }
        if isinstance(value, (list, tuple)):
            return [self._encode_child(child) for child in value]
        return value

    def _encode_original_node(self, original: Any) -> Any:
        """Convert and Merkle-encode in one traversal."""

        if isinstance(original, Mapping):
            return {
                str(key): (
                    {_REF_KEY: self._intern_original(child)}
                    if _is_container(child) and str(key) in _ARTIFACT_AWARE_CAS_KEYS
                    else _json_safe(child, self._safe_cache)
                )
                for key, child in original.items()
            }
        if isinstance(original, (list, tuple)):
            return [
                (
                    {_REF_KEY: self._intern_original(child)}
                    if _is_container(child)
                    else _json_safe(child, self._safe_cache)
                )
                for child in original
            ]
        return _json_safe(original, self._safe_cache)

    def _intern_original(self, original: Any) -> str:
        if _is_container(original):
            cached = self._identity_cache.get(id(original))
            if cached is not None and cached[0] is original:
                return cached[1]
        encoded = self._encode_original_node(original)
        # Hash the lossless Merkle node, not the repeatedly expanded logical
        # subtree.  Child refs already commit to their complete contents, so
        # this remains content-addressed while avoiding O(depth * bytes).
        canonical = _canonical_safe_bytes(encoded)
        ref = _REF_PREFIX + hashlib.sha256(canonical).hexdigest()
        if ref not in self._entries:
            stored = _store_bytes(encoded)
            self._entries[ref] = stored
            self._physical_bytes += len(stored)
        if _is_container(original):
            self._identity_cache[id(original)] = (original, ref)
        return ref

    def _intern_safe(self, safe: Any) -> str:
        encoded = self._encode_node(safe)
        canonical = _canonical_safe_bytes(encoded)
        ref = _REF_PREFIX + hashlib.sha256(canonical).hexdigest()
        if ref not in self._entries:
            stored = _store_bytes(encoded)
            self._entries[ref] = stored
            self._physical_bytes += len(stored)
        return ref

    def intern(self, value: Any) -> str:
        """Intern one logical JSON value and return its full SHA-256 ref."""

        return self._intern_original(value)

    def digest(self) -> str:
        return _mapping_content_digest(self._entries)

    def serialized_size(self) -> int:
        return len(serialized_json_bytes(self.entries))


class ChunkedContentAddressedStore(ContentAddressedStore):
    """A bounded-memory CAS with one reusable external-merge finalization.

    Active entries are flushed to sorted private chunks. :meth:`finalize`
    merges those chunks exactly once into an immutable runtime file while it
    computes the logical mapping digest and verifies duplicate refs. All later
    digest and iteration calls reuse that file instead of rebuilding a merge
    tree.
    """

    MERGE_FAN_IN = 32

    def __init__(
        self,
        directory: str | Path | None = None,
        *,
        chunk_entries: int = 100_000,
        max_active_entries: int = 100_000,
        max_active_physical_bytes: int = 64 * 1024 * 1024,
        merge_fan_in: int = MERGE_FAN_IN,
    ) -> None:
        if min(chunk_entries, max_active_entries, max_active_physical_bytes) <= 0:
            raise ValueError("chunk and active safety limits must be positive")
        if not 2 <= merge_fan_in <= 64:
            raise ValueError("merge_fan_in must be between 2 and 64")
        super().__init__()
        # These are physical safety settings, not candidate-count policies.
        self.chunk_entries = int(chunk_entries)
        self.max_active_entries = int(max_active_entries)
        self.max_active_physical_bytes = int(max_active_physical_bytes)
        self.merge_fan_in = int(merge_fan_in)
        self.peak_open_chunk_streams = 0
        self.merge_group_count = 0
        self.merge_pass_count = 0
        self.finalization_count = 0
        self._temporary_merges: list[Path] = []
        self._chunk_dir = Path(directory) if directory is not None else Path(
            tempfile.mkdtemp(prefix="ashare-cas-")
        )
        self._chunk_dir.mkdir(parents=True, exist_ok=True)
        self._chunks: list[Path] = []
        self._chunk_sequence = 0
        self._finalized_path: Path | None = None
        self._finalized_digest: str | None = None
        self._finalized_entry_count: int | None = None
        self._finalized_physical_bytes: int | None = None
        self._finalization_failed = False

    @property
    def chunk_count(self) -> int:
        return len(self._chunks)

    @property
    def finalized_path(self) -> Path | None:
        return self._finalized_path

    @property
    def is_finalized(self) -> bool:
        return self._finalized_path is not None

    def intern(self, value: Any) -> str:
        if self.is_finalized or self._finalization_failed:
            raise RuntimeError("cannot add entries after CAS finalization")
        return super().intern(value)

    def flush_chunk(self, *, force: bool = False) -> Path | None:
        """Persist the active physical chunk; ``force`` documents the boundary."""

        del force
        if self.is_finalized or self._finalization_failed:
            raise RuntimeError("cannot flush entries after CAS finalization")
        if not self._entries:
            return None
        path = self._chunk_dir / f"chunk-{self._chunk_sequence:08d}.cas"
        self._chunk_sequence += 1
        try:
            with path.open("xb") as handle:
                for ref, value in super().iter_entries_sorted():
                    handle.write(
                        ref.encode("ascii") + b"\t" + base64.b64encode(value) + b"\n"
                    )
        except BaseException:
            path.unlink(missing_ok=True)
            raise
        self._chunks.append(path)
        self._entries.clear()
        self._physical_bytes = 0
        self.clear_identity_cache()
        return path

    def flush_chunk_if_needed(self, *, force: bool = False) -> Path | None:
        """Apply physical safety limits; callers explicitly own candidate batches."""

        if (
            force
            or len(self._entries) >= self.chunk_entries
            or len(self._entries) >= self.max_active_entries
            or self._physical_bytes >= self.max_active_physical_bytes
        ):
            return self.flush_chunk()
        return None

    @staticmethod
    def _merge_streams(
        streams: list[Iterator[tuple[str, bytes]]],
    ) -> Iterator[tuple[str, bytes]]:
        heap: list[tuple[str, int, bytes]] = []
        for index, stream in enumerate(streams):
            try:
                ref, value = next(stream)
            except StopIteration:
                continue
            heapq.heappush(heap, (ref, index, value))
        while heap:
            ref, index, value = heapq.heappop(heap)
            same = [(index, value)]
            while heap and heap[0][0] == ref:
                _, other_index, other_value = heapq.heappop(heap)
                same.append((other_index, other_value))
            if any(other_value != value for _, other_value in same):
                raise ValueError(f"conflicting physical bytes for duplicate ref: {ref}")
            yield ref, value
            for stream_index, _ in same:
                try:
                    next_ref, next_value = next(streams[stream_index])
                except StopIteration:
                    continue
                heapq.heappush(heap, (next_ref, stream_index, next_value))

    @staticmethod
    def _chunk_entries_from_handle(handle: Any) -> Iterator[tuple[str, bytes]]:
        for line in handle:
            ref, encoded = line.rstrip(b"\n").split(b"\t", 1)
            yield ref.decode("ascii"), base64.b64decode(encoded)

    def _merge_group(
        self,
        paths: list[Path],
        output: Path,
        *,
        resource_probe: ResourceProbe | None,
        probe_interval_bytes: int,
        final: bool = False,
    ) -> tuple[str | None, int, int]:
        phase = "cas_final_merge" if final else "cas_intermediate_merge_group"
        if resource_probe is not None:
            resource_probe(f"{phase}_start")
        digest = hashlib.sha256() if final else None
        if digest is not None:
            digest.update(b"{")
        entry_count = 0
        physical_bytes = 0
        bytes_since_probe = 0
        output.unlink(missing_ok=True)
        try:
            with ExitStack() as stack:
                handles = [stack.enter_context(path.open("rb")) for path in paths]
                self.peak_open_chunk_streams = max(
                    self.peak_open_chunk_streams, len(handles)
                )
                streams = [self._chunk_entries_from_handle(handle) for handle in handles]
                with output.open("xb") as target:
                    for ref, value in self._merge_streams(streams):
                        line = (
                            ref.encode("ascii")
                            + b"\t"
                            + base64.b64encode(value)
                            + b"\n"
                        )
                        target.write(line)
                        if digest is not None:
                            if entry_count:
                                digest.update(b",")
                            digest.update(_canonical_safe_bytes(ref))
                            digest.update(b":")
                            digest.update(_physical_store_value_bytes(value))
                        entry_count += 1
                        physical_bytes += len(value)
                        bytes_since_probe += len(line)
                        if (
                            resource_probe is not None
                            and bytes_since_probe >= probe_interval_bytes
                        ):
                            resource_probe(f"{phase}_output_interval")
                            bytes_since_probe = 0
                    target.flush()
            if digest is not None:
                digest.update(b"}")
            if resource_probe is not None:
                resource_probe(f"{phase}_complete")
        except BaseException:
            output.unlink(missing_ok=True)
            raise
        self.merge_group_count += 1
        return digest.hexdigest() if digest is not None else None, entry_count, physical_bytes

    def finalize(
        self,
        *,
        resource_probe: ResourceProbe | None = None,
        probe_interval_bytes: int = FINALIZATION_PROBE_INTERVAL_BYTES,
    ) -> Path:
        """Create and cache the sole sorted runtime store and its digest.

        Duplicate refs with equal bytes are deduplicated by the merge. A
        conflicting duplicate fails closed. Intermediate files are removed as
        soon as a complete successor exists; a failed finalization removes all
        partial/intermediate output and leaves cleanup of surviving source
        chunks to :meth:`close`.
        """

        if probe_interval_bytes <= 0:
            raise ValueError("probe_interval_bytes must be positive")
        if self._finalized_path is not None:
            return self._finalized_path
        if self._finalization_failed:
            raise RuntimeError("CAS finalization previously failed")
        self.flush_chunk(force=True)
        paths = list(self._chunks)
        partial = self._chunk_dir / "finalized.cas.partial"
        final_path = self._chunk_dir / "finalized.cas"
        partial.unlink(missing_ok=True)
        final_path.unlink(missing_ok=True)
        level = 0
        try:
            if resource_probe is not None:
                resource_probe("cas_finalize_start")
            while len(paths) > self.merge_fan_in:
                self.merge_pass_count += 1
                next_paths: list[Path] = []
                for group_index, start in enumerate(
                    range(0, len(paths), self.merge_fan_in)
                ):
                    group = paths[start : start + self.merge_fan_in]
                    output = self._chunk_dir / (
                        f"merge-{level:04d}-{group_index:08d}.cas"
                    )
                    self._merge_group(
                        group,
                        output,
                        resource_probe=resource_probe,
                        probe_interval_bytes=probe_interval_bytes,
                    )
                    self._temporary_merges.append(output)
                    next_paths.append(output)
                    # Each completed group is a durable sorted replacement for
                    # its inputs; releasing them bounds temporary disk growth.
                    for path in group:
                        path.unlink(missing_ok=True)
                        if path in self._chunks:
                            self._chunks.remove(path)
                        if path in self._temporary_merges:
                            self._temporary_merges.remove(path)
                paths = next_paths
                level += 1
            self.merge_pass_count += 1
            digest, entry_count, physical_bytes = self._merge_group(
                paths,
                partial,
                resource_probe=resource_probe,
                probe_interval_bytes=probe_interval_bytes,
                final=True,
            )
            assert digest is not None
            if resource_probe is not None:
                # This is deliberately before promotion. A hard resource gate
                # therefore cannot leave a finalized file behind.
                resource_probe("cas_finalized_store_completion")
            os.replace(partial, final_path)
            for path in paths:
                path.unlink(missing_ok=True)
            self._chunks.clear()
            self._temporary_merges.clear()
            self._finalized_path = final_path
            self._finalized_digest = digest
            self._finalized_entry_count = entry_count
            self._finalized_physical_bytes = physical_bytes
            self.finalization_count += 1
            return final_path
        except BaseException:
            partial.unlink(missing_ok=True)
            final_path.unlink(missing_ok=True)
            for path in self._temporary_merges:
                path.unlink(missing_ok=True)
            self._temporary_merges.clear()
            self._finalization_failed = True
            raise

    def iter_entries_sorted(
        self,
        *,
        resource_probe: ResourceProbe | None = None,
        probe_interval_bytes: int = FINALIZATION_PROBE_INTERVAL_BYTES,
    ) -> Iterator[tuple[str, bytes]]:
        """Read the finalized sorted file directly without another merge."""

        if probe_interval_bytes <= 0:
            raise ValueError("probe_interval_bytes must be positive")
        path = self.finalize(
            resource_probe=resource_probe,
            probe_interval_bytes=probe_interval_bytes,
        )
        if resource_probe is not None:
            resource_probe("cas_finalized_store_iteration_start")
        bytes_since_probe = 0
        with path.open("rb") as handle:
            for ref, value in self._chunk_entries_from_handle(handle):
                yield ref, value
                bytes_since_probe += len(value)
                if (
                    resource_probe is not None
                    and bytes_since_probe >= probe_interval_bytes
                ):
                    resource_probe("cas_finalized_store_iteration_interval")
                    bytes_since_probe = 0
        if resource_probe is not None:
            resource_probe("cas_finalized_store_iteration_complete")

    def digest(
        self,
        *,
        resource_probe: ResourceProbe | None = None,
        probe_interval_bytes: int = FINALIZATION_PROBE_INTERVAL_BYTES,
    ) -> str:
        self.finalize(
            resource_probe=resource_probe,
            probe_interval_bytes=probe_interval_bytes,
        )
        assert self._finalized_digest is not None
        return self._finalized_digest

    def __len__(self) -> int:
        return self.entry_count

    @property
    def entry_count(self) -> int:
        self.finalize()
        assert self._finalized_entry_count is not None
        return self._finalized_entry_count

    @property
    def active_entry_count(self) -> int:
        return len(self._entries)

    @property
    def active_physical_byte_count(self) -> int:
        return self._physical_bytes

    @property
    def physical_byte_count(self) -> int:
        self.finalize()
        assert self._finalized_physical_bytes is not None
        return self._finalized_physical_bytes

    def close(self, *, cleanup: bool = True) -> None:
        if cleanup:
            owned_paths = {
                *self._chunks,
                *self._temporary_merges,
                self._chunk_dir / "finalized.cas",
                self._chunk_dir / "finalized.cas.partial",
            }
            for pattern in ("merge-*.cas",):
                owned_paths.update(self._chunk_dir.glob(pattern))
            for path in owned_paths:
                path.unlink(missing_ok=True)
            self._chunks.clear()
            self._temporary_merges.clear()
            try:
                self._chunk_dir.rmdir()
            except OSError:
                pass
        self._entries.clear()
        self._physical_bytes = 0
        self._finalized_path = None
        self._finalized_digest = None
        self._finalized_entry_count = None
        self._finalized_physical_bytes = None
        self._finalization_failed = False
        self.clear_identity_cache()



def _store_argument(
    store: ContentAddressedStore | Mapping[str, Any] | None,
) -> tuple[ContentAddressedStore, MutableMapping[str, Any] | None, bool]:
    if isinstance(store, ContentAddressedStore):
        return store, None, False
    if store is None:
        return ContentAddressedStore(), None, True
    if not isinstance(store, Mapping):
        raise TypeError("store must be a ContentAddressedStore or mapping")
    # A mutable mapping is synchronized after normalization for callers that
    # intentionally supply their own snapshot-local store.
    target = store if isinstance(store, MutableMapping) else None
    return ContentAddressedStore(store), target, False


