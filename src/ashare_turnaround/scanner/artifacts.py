def _payload(value: Any, *, method: str) -> dict[str, Any]:
    if isinstance(value, FeatureVector):
        # Read nested provenance directly.  Normalization only replaces fields
        # on these new top-level dictionaries and never mutates the vector.
        return _feature_vector_payload(value)
    candidate = getattr(value, method, None)
    if callable(candidate):
        result = candidate()
        if not isinstance(result, Mapping):
            raise TypeError(f"{method}() must return a mapping")
        return copy.deepcopy(dict(result))
    if not isinstance(value, Mapping):
        raise TypeError("artifact payload must be a FeatureVector or mapping")
    return copy.deepcopy(dict(value))


def _evidence_payload(value: Any) -> dict[str, Any]:
    if isinstance(value, FeatureEvidence):
        return dict(value.as_dict(deep_copy=False))
    if not isinstance(value, Mapping):
        raise TypeError("feature evidence must be a FeatureEvidence or mapping")
    # Only top-level reference fields are removed below.  A shallow copy
    # preserves shared nested JSON objects long enough for the store to
    # recognize them without retaining those source objects after a streamed
    # candidate is released.
    return dict(value)


def _normalize_evidence(value: Any, store: ContentAddressedStore) -> dict[str, Any]:
    evidence = _evidence_payload(value)
    for field_name in _EVIDENCE_REFERENCE_FIELDS:
        logical = evidence.pop(
            field_name,
            () if field_name in _EVIDENCE_SEQUENCE_FIELDS else {},
        )
        ref_name = f"{field_name}_ref"
        if ref_name in evidence:
            raise ValueError(f"evidence already contains reserved field {ref_name}")
        evidence[ref_name] = store.intern(logical)
    return evidence


def normalize_feature_vector(
    vector: FeatureVector | Mapping[str, Any],
    *,
    store: ContentAddressedStore | Mapping[str, Any] | None = None,
    provenance_store: ContentAddressedStore | Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Normalize one vector while retaining all logical evidence fields.

    A standalone call owns a small local ``provenance_store`` embedded in the
    returned record, making the result immediately expandable.  Snapshot
    callers pass one shared ``ContentAddressedStore`` so all vectors share it.
    ``provenance_store`` is accepted as a descriptive alias for ``store``.
    """

    if store is not None and provenance_store is not None:
        raise TypeError("pass only one of store or provenance_store")
    selected_store = store if store is not None else provenance_store
    builder, target, owns_store = _store_argument(selected_store)
    payload = _payload(vector, method="as_dict")
    evidence = payload.get("evidence", {})
    if not isinstance(evidence, Mapping):
        raise ValueError("feature vector evidence must be a mapping")
    payload["evidence"] = {
        str(name): _normalize_evidence(item, builder)
        for name, item in evidence.items()
    }
    for field_name in _VECTOR_PAYLOAD_FIELDS:
        if field_name not in payload:
            continue
        logical = payload.pop(field_name)
        ref_name = f"{field_name}_ref"
        if ref_name in payload:
            raise ValueError(f"vector already contains reserved field {ref_name}")
        payload[ref_name] = builder.intern(logical)
    builder.clear_identity_cache()
    if target is not None:
        target.clear()
        target.update(builder.entries)
    if owns_store:
        payload["provenance_store"] = builder.physical_entries
    return payload


def _normalize_replay_payload(
    value: Any,
    store: ContentAddressedStore,
) -> dict[str, Any]:
    payload = _payload(value, method="artifact_dict")
    if payload.get("artifact_layout_version") == NORMALIZED_ARTIFACT_LAYOUT_VERSION:
        payload = expand_normalized_replay_artifact(payload)
    existing_store = payload.pop("provenance_store", None)
    if existing_store is not None and not isinstance(existing_store, Mapping):
        raise ValueError("provenance_store must be a mapping")
    vectors = payload.get("vectors", [])
    if not isinstance(vectors, (list, tuple)):
        raise ValueError("replay vectors must be an array")
    payload["vectors"] = [normalize_feature_vector(item, store=store) for item in vectors]
    payload["artifact_layout_version"] = NORMALIZED_ARTIFACT_LAYOUT_VERSION
    payload["provenance_store"] = store.physical_entries
    return payload


def normalize_replay_artifact(
    artifact: Any,
    *,
    store: ContentAddressedStore | Mapping[str, Any] | None = None,
    provenance_store: ContentAddressedStore | Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Return a normalized physical representation of a replay artifact."""

    if store is not None and provenance_store is not None:
        raise TypeError("pass only one of store or provenance_store")
    selected_store = store if store is not None else provenance_store
    builder, target, _ = _store_argument(selected_store)
    result = _normalize_replay_payload(artifact, builder)
    if target is not None:
        target.clear()
        target.update(builder.entries)
    return result


def normalize_feature_vectors(
    vectors: Iterable[FeatureVector | Mapping[str, Any]],
) -> dict[str, Any]:
    """Normalize a vector collection with one shared snapshot-local store."""

    store = ContentAddressedStore()
    normalized = [normalize_feature_vector(vector, store=store) for vector in vectors]
    return {
        "artifact_layout_version": NORMALIZED_ARTIFACT_LAYOUT_VERSION,
        "vectors": normalized,
        "provenance_store": store.physical_entries,
    }


def normalize_snapshot_payload(snapshot: Mapping[str, Any]) -> dict[str, Any]:
    """Normalize one validation snapshot, keeping its outer audit envelope."""

    if not isinstance(snapshot, Mapping):
        raise TypeError("snapshot must be a mapping")
    payload = copy.deepcopy(dict(snapshot))
    if payload.get("artifact_layout_version") == NORMALIZED_ARTIFACT_LAYOUT_VERSION:
        payload = expand_normalized_snapshot(payload)
    store = ContentAddressedStore()
    replay = payload.get("replay")
    if isinstance(replay, Mapping):
        payload["replay"] = _normalize_replay_payload(replay, store)
    payload["artifact_layout_version"] = NORMALIZED_ARTIFACT_LAYOUT_VERSION
    return payload


def normalize_artifact(value: Any) -> dict[str, Any]:
    """Friendly dispatcher for replay or validation-snapshot payloads."""

    if isinstance(value, FeatureVector):
        return normalize_feature_vector(value)
    if hasattr(value, "artifact_dict"):
        return normalize_replay_artifact(value)
    if isinstance(value, Mapping) and "replay" in value:
        return normalize_snapshot_payload(value)
    return normalize_replay_artifact(value)


def _is_ref_marker(value: Any) -> bool:
    return (
        isinstance(value, Mapping)
        and set(value) == {_REF_KEY}
        and isinstance(value.get(_REF_KEY), str)
        and value.get(_REF_KEY, "").startswith(_REF_PREFIX)
    )


def _expand_node(
    value: Any,
    store: Mapping[str, Any],
    active: tuple[str, ...] = (),
) -> Any:
    if _is_compressed_wrapper(value):
        compressed = _COMPRESSED_PREFIX + value["data"].encode("ascii")
        return _expand_node(_decode_store_bytes(compressed), store, active)
    if _is_ref_marker(value):
        ref = str(value[_REF_KEY])
        if ref in active:
            raise ValueError(f"cyclic normalized reference: {ref}")
        if ref not in store:
            raise KeyError(f"missing normalized provenance ref: {ref}")
        return _expand_node(store[ref], store, (*active, ref))
    if isinstance(value, Mapping):
        return {str(key): _expand_node(item, store, active) for key, item in value.items()}
    if isinstance(value, list):
        return [_expand_node(item, store, active) for item in value]
    return copy.deepcopy(value)


def _expand_ref(ref: Any, store: Mapping[str, Any]) -> Any:
    if not isinstance(ref, str) or not ref.startswith(_REF_PREFIX):
        raise ValueError(f"invalid normalized reference: {ref!r}")
    if ref not in store:
        raise KeyError(f"missing normalized provenance ref: {ref}")
    return _expand_node(store[ref], store, (ref,))


def _merge_overlay(base: Any, overlay: Any) -> Any:
    if isinstance(base, Mapping) and isinstance(overlay, Mapping):
        merged = copy.deepcopy(dict(base))
        for key, value in overlay.items():
            merged[str(key)] = (
                _merge_overlay(merged[key], value)
                if key in merged
                else copy.deepcopy(value)
            )
        return merged
    return copy.deepcopy(overlay)


def _restore_evidence_sequences(evidence: dict[str, Any]) -> dict[str, Any]:
    for field_name in _EVIDENCE_SEQUENCE_FIELDS:
        if field_name in evidence and isinstance(evidence[field_name], list):
            # FeatureEvidence.as_dict() exposes these tuple-typed contract
            # fields.  Restoring them makes object-level expansion equal to
            # the legacy Python payload, while JSON-level canonical equality
            # remains list based as required by the physical format.
            evidence[field_name] = tuple(evidence[field_name])
    return evidence


def _restore_legacy_tuple_shapes(value: Any, path: str = "") -> Any:
    """Restore tuple-valued fields exposed by existing Python contracts."""

    if isinstance(value, Mapping):
        result: dict[str, Any] = {}
        for key, child in value.items():
            text = str(key)
            child_path = f"{path}.{text}"
            restored = _restore_legacy_tuple_shapes(child, child_path)
            tuple_field = text in {
                "lookbacks",
                "enabled_groups",
                "mandatory_components",
                "included_optional_components",
                "lookback_sessions",
                "lookback",
            }
            marker = "low_attention_v2_evidence"
            remainder = (
                child_path.split(marker, 1)[1].strip(".").split(".")
                if marker in child_path
                else []
            )
            metadata_evidence_field = (
                text in _EVIDENCE_SEQUENCE_FIELDS and len(remainder) == 2
            )
            if (tuple_field or metadata_evidence_field) and isinstance(restored, list):
                restored = tuple(restored)
            result[text] = restored
        return result
    if isinstance(value, list):
        return [_restore_legacy_tuple_shapes(item, f"{path}[]") for item in value]
    return value


def expand_normalized_vector(
    vector: Mapping[str, Any],
    provenance_store: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Expand one normalized vector back to the legacy logical payload."""

    if not isinstance(vector, Mapping):
        raise TypeError("normalized vector must be a mapping")
    payload = copy.deepcopy(dict(vector))
    embedded_store = payload.pop("provenance_store", None)
    store = provenance_store if provenance_store is not None else embedded_store
    if store is None:
        # A legacy vector with no refs does not need a store.
        store = {}
    if not isinstance(store, Mapping):
        raise ValueError("provenance_store must be a mapping")
    payload.pop("artifact_layout_version", None)
    evidence_payload = payload.get("evidence", {})
    if not isinstance(evidence_payload, Mapping):
        raise ValueError("normalized vector evidence must be a mapping")
    expanded_evidence: dict[str, Any] = {}
    for name, raw in evidence_payload.items():
        evidence = _evidence_payload(raw)
        for field_name in _EVIDENCE_REFERENCE_FIELDS:
            ref_name = f"{field_name}_ref"
            if ref_name in evidence:
                logical = _expand_ref(evidence.pop(ref_name), store)
            elif field_name in evidence:
                logical = evidence[field_name]
            else:
                logical = () if field_name in _EVIDENCE_SEQUENCE_FIELDS else {}
            evidence[field_name] = logical
        overlay = evidence.pop("provenance_overlay", None)
        if overlay is not None:
            evidence["provenance"] = _merge_overlay(evidence["provenance"], overlay)
        expanded_evidence[str(name)] = _restore_evidence_sequences(evidence)
    payload["evidence"] = expanded_evidence
    for field_name in _VECTOR_PAYLOAD_FIELDS:
        ref_name = f"{field_name}_ref"
        if ref_name in payload:
            payload[field_name] = _expand_ref(payload.pop(ref_name), store)
    return _restore_legacy_tuple_shapes(payload)


def expand_normalized_replay_artifact(artifact: Mapping[str, Any]) -> dict[str, Any]:
    """Expand a normalized replay artifact without changing its semantics."""

    if not isinstance(artifact, Mapping):
        raise TypeError("normalized replay artifact must be a mapping")
    payload = copy.deepcopy(dict(artifact))
    store = payload.pop("provenance_store", None)
    if store is None:
        store = {}
    if not isinstance(store, Mapping):
        raise ValueError("provenance_store must be a mapping")
    payload.pop("artifact_layout_version", None)
    payload.pop("deterministic_digests", None)
    vectors = payload.get("vectors", [])
    if not isinstance(vectors, (list, tuple)):
        raise ValueError("normalized replay vectors must be an array")
    payload["vectors"] = [expand_normalized_vector(item, store) for item in vectors]
    return payload


def expand_normalized_snapshot(snapshot: Mapping[str, Any]) -> dict[str, Any]:
    """Expand a normalized validation snapshot to its legacy envelope."""

    if not isinstance(snapshot, Mapping):
        raise TypeError("normalized snapshot must be a mapping")
    payload = copy.deepcopy(dict(snapshot))
    payload.pop("artifact_layout_version", None)
    replay = payload.get("replay")
    if isinstance(replay, Mapping):
        payload["replay"] = expand_normalized_replay_artifact(replay)
    elif "vectors" in payload:
        payload = expand_normalized_replay_artifact(payload)
    return payload


def feature_vector_from_payload(payload: Mapping[str, Any]) -> FeatureVector:
    """Rehydrate a logical vector for PIT validation of a normalized payload."""

    if not isinstance(payload, Mapping):
        raise TypeError("feature vector payload must be a mapping")
    evidence: dict[str, FeatureEvidence] = {}
    evidence_field_names = {item.name for item in __import__("dataclasses").fields(FeatureEvidence)}
    for name, raw in payload.get("evidence", {}).items():
        record = _evidence_payload(raw)
        components = dict(record.get("components") or {})
        for key in (
            "start_session",
            "end_session",
            "stock_start",
            "stock_end",
            "benchmark_start",
            "benchmark_end",
            "benchmark_id",
            "stock_return",
            "benchmark_return",
            "excess_return",
        ):
            if key in record:
                components.setdefault(key, record[key])
        kwargs = {
            key: copy.deepcopy(value)
            for key, value in record.items()
            if key in evidence_field_names
        }
        kwargs.setdefault("feature", str(name))
        kwargs.setdefault("value", payload.get("values", {}).get(name))
        for field_name in _EVIDENCE_SEQUENCE_FIELDS:
            if field_name in kwargs and isinstance(kwargs[field_name], list):
                kwargs[field_name] = tuple(kwargs[field_name])
        kwargs["components"] = components
        evidence[str(name)] = FeatureEvidence(**kwargs)
    vector_field_names = {item.name for item in __import__("dataclasses").fields(FeatureVector)}
    kwargs = {
        key: copy.deepcopy(value)
        for key, value in payload.items()
        if key in vector_field_names and key != "evidence"
    }
    kwargs.setdefault("ts_code", str(payload.get("ts_code", "")))
    kwargs.setdefault("as_of_date", str(payload.get("as_of_date", "")))
    kwargs["evidence"] = evidence
    for field_name in ("risk_flags", "rejected_reasons", "unknown_features"):
        if field_name in kwargs and kwargs[field_name] is None:
            kwargs[field_name] = []
    return FeatureVector(**kwargs)


def _semantic_clean(value: Any, *, key: str | None = None) -> Any:
    if key is not None and key.casefold() in _RUNTIME_KEYS:
        return None
    if isinstance(value, Mapping):
        result: dict[str, Any] = {}
        for raw_key, item in value.items():
            text = str(raw_key)
            if text.casefold() in _RUNTIME_KEYS:
                continue
            cleaned = _semantic_clean(item, key=text)
            if cleaned is not _DROP:
                result[text] = cleaned
        return result
    if isinstance(value, (list, tuple)):
        return [_semantic_clean(item) for item in value]
    if isinstance(value, (set, frozenset)):
        return sorted((_semantic_clean(item) for item in value), key=canonical_json_bytes)
    return value


