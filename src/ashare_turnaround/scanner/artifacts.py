def _json_safe(value: Any, _memo: dict[int, Any] | None = None) -> Any:
    """Convert common pandas/numpy values to finite JSON-compatible values."""

    memo = _memo if _memo is not None else {}
    if value is None or value is pd.NA or value is pd.NaT:
        return None
    if isinstance(value, (pd.Timestamp, datetime, date)):
        timestamp = pd.Timestamp(value)
        if timestamp.tzinfo is not None:
            timestamp = timestamp.tz_localize(None)
        return timestamp.isoformat()
    if isinstance(value, Mapping):
        object_key = id(value)
        if object_key in memo:
            return memo[object_key]
        result: dict[str, Any] = {}
        memo[object_key] = result
        result.update({str(key): _json_safe(item, memo) for key, item in value.items()})
        return result
    if isinstance(value, (list, tuple)):
        object_key = id(value)
        if object_key in memo:
            return memo[object_key]
        result_list: list[Any] = []
        memo[object_key] = result_list
        result_list.extend(_json_safe(item, memo) for item in value)
        return result_list
    if isinstance(value, (set, frozenset)):
        values = [_json_safe(item, memo) for item in value]
        return sorted(values, key=lambda item: canonical_json_bytes(item))
    if isinstance(value, bool):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if hasattr(value, "item") and not isinstance(value, (str, bytes)):
        try:
            return _json_safe(value.item(), memo)
        except (TypeError, ValueError, OverflowError):
            pass
    if hasattr(value, "tolist") and not isinstance(value, (str, bytes)):
        try:
            return _json_safe(value.tolist(), memo)
        except (TypeError, ValueError):
            pass
    try:
        missing = pd.isna(value)
        if isinstance(missing, bool) and missing:
            return None
    except (TypeError, ValueError):
        pass
    return value


def _canonical_safe_bytes(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")


def canonical_json_bytes(value: Any) -> bytes:
    """Return the canonical UTF-8 JSON bytes used by every content hash."""

    return _canonical_safe_bytes(_json_safe(value))


def canonical_json(value: Any) -> str:
    return canonical_json_bytes(value).decode("utf-8")


def content_digest(value: Any) -> str:
    """Return a full SHA-256 hex digest over canonical JSON."""

    return hashlib.sha256(canonical_json_bytes(value)).hexdigest()


def content_ref(value: Any) -> str:
    """Return the canonical content-address format used in normalized files."""

    return _REF_PREFIX + content_digest(value)


def _mapping_content_digest(value: Mapping[str, Any]) -> str:
    """Hash a large mapping in bounded memory while preserving JSON ordering."""

    digest = hashlib.sha256()
    digest.update(b"{")
    for index, key in enumerate(sorted(value, key=str)):
        if index:
            digest.update(b",")
        digest.update(_canonical_safe_bytes(str(key)))
        digest.update(b":")
        child = value[key]
        digest.update(
            _physical_store_value_bytes(child)
            if isinstance(child, bytes)
            else canonical_json_bytes(child)
        )
    digest.update(b"}")
    return digest.hexdigest()


def serialized_json_bytes(value: Any) -> bytes:
    """Return deterministic bytes matching the pretty JSON artifact writer."""

    return (
        json.dumps(
            _json_safe(value),
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
        + "\n"
    ).encode("utf-8")


def _is_container(value: Any) -> bool:
    return isinstance(value, (Mapping, list, tuple))


def _store_bytes(value: Any) -> bytes:
    """Encode one node without defeating cross-node stream compression.

    Earlier artifacts compressed every node independently at zlib level 9 and
    then base64 encoded it.  Besides being CPU intensive, that hid repetition
    between neighbouring nodes from the final compressor.  The decoder still
    accepts that legacy representation, but newly built stores retain canonical
    plain JSON bytes and are compressed once by the snapshot writer.
    """

    return _canonical_safe_bytes(value)


def _is_compressed_bytes(value: Any) -> bool:
    return isinstance(value, bytes) and value.startswith(_COMPRESSED_PREFIX)


def _compressed_wrapper(value: bytes) -> dict[str, str]:
    return {
        "encoding": _COMPRESSED_ENCODING,
        "data": value[len(_COMPRESSED_PREFIX) :].decode("ascii"),
    }


def _is_compressed_wrapper(value: Any) -> bool:
    return (
        isinstance(value, Mapping)
        and value.get("encoding") == _COMPRESSED_ENCODING
        and isinstance(value.get("data"), str)
    )


def _decode_store_bytes(value: bytes) -> Any:
    raw = (
        zlib.decompress(base64.b64decode(value[len(_COMPRESSED_PREFIX) :]))
        if _is_compressed_bytes(value)
        else value
    )
    return json.loads(raw.decode("utf-8"))


def _decode_store_value(value: Any) -> Any:
    if _is_compressed_bytes(value):
        return _decode_store_bytes(value)
    if _is_compressed_wrapper(value):
        compressed = _COMPRESSED_PREFIX + value["data"].encode("ascii")
        return _decode_store_bytes(compressed)
    return copy.deepcopy(value)


def _physical_store_value_bytes(value: Any) -> bytes:
    if isinstance(value, bytes):
        return (
            _canonical_safe_bytes(_compressed_wrapper(value))
            if _is_compressed_bytes(value)
            else value
        )
    return canonical_json_bytes(value)


class ContentAddressedStore:
    """Snapshot-local Merkle-style store keyed by logical JSON content.

    Hashes are computed from the original logical subtree.  Store entries may
    contain references to child entries; this makes repeated nested objects
    (for example TrendSummary observations) physically unique as well as
    repeated top-level provenance objects.
    """

    def __init__(self, entries: Mapping[str, Any] | None = None) -> None:
        # Encoded nodes are kept as canonical JSON bytes in memory.  Parsed
        # Python trees multiply the resident set dramatically for a 100-stock
        # stream even when the final JSON is only a few hundred MiB.
        self._entries: dict[str, bytes] = {}
        # This cache is intentionally scoped by normalize_feature_vector;
        # retaining source objects across streamed candidates would defeat the
        # memory benefit of the physical store.
        self._identity_cache: dict[int, tuple[Any, str]] = {}
        # Share JSON-safe conversions across aliased nested provenance within
        # one candidate.  TrendSummary deliberately reuses observations and
        # source chains across component evidence records.
        self._safe_cache: dict[int, Any] = {}
        if entries is not None:
            for key, value in entries.items():
                ref = str(key)
                if not ref.startswith(_REF_PREFIX):
                    raise ValueError(f"invalid content-addressed ref: {ref!r}")
                if isinstance(value, bytes):
                    self._entries[ref] = bytes(value)
                elif _is_compressed_wrapper(value):
                    compressed = _COMPRESSED_PREFIX + value["data"].encode("ascii")
                    self._entries[ref] = compressed
                else:
                    self._entries[ref] = _store_bytes(_json_safe(value))

    @property
    def entries(self) -> dict[str, Any]:
        return {
            key: _decode_store_bytes(value)
            for key, value in sorted(self._entries.items())
        }

    @property
    def physical_entries(self) -> dict[str, Any]:
        """Return JSON-native physical store values for an artifact payload."""

        return {
            key: (
                _compressed_wrapper(value)
                if _is_compressed_bytes(value)
                else _decode_store_bytes(value)
            )
            for key, value in sorted(self._entries.items())
        }

    def entries_view(self) -> Mapping[str, bytes]:
        """Return a sorted shallow view for streaming writers."""

        return {key: self._entries[key] for key in sorted(self._entries)}

    def __len__(self) -> int:
        return len(self._entries)

    def clear_identity_cache(self) -> None:
        self._identity_cache.clear()
        self._safe_cache.clear()

    def _encode_child(self, value: Any) -> Any:
        if _is_container(value):
            return {_REF_KEY: self._intern_safe(value)}
        return value

    def _encode_node(self, value: Any) -> Any:
        if isinstance(value, Mapping):
            return {
                str(key): (
                    self._encode_child(child)
                    if str(key) in _ARTIFACT_AWARE_CAS_KEYS
                    else child
                )
                for key, child in value.items()
            }
        if isinstance(value, (list, tuple)):
            return [self._encode_child(child) for child in value]
        return value

    def _encode_original_node(self, original: Any) -> Any:
        """Convert and Merkle-encode in one traversal."""

        if isinstance(original, Mapping):
            return {
                str(key): (
                    {_REF_KEY: self._intern_original(child)}
                    if _is_container(child) and str(key) in _ARTIFACT_AWARE_CAS_KEYS
                    else _json_safe(child, self._safe_cache)
                )
                for key, child in original.items()
            }
        if isinstance(original, (list, tuple)):
            return [
                (
                    {_REF_KEY: self._intern_original(child)}
                    if _is_container(child)
                    else _json_safe(child, self._safe_cache)
                )
                for child in original
            ]
        return _json_safe(original, self._safe_cache)

    def _intern_original(self, original: Any) -> str:
        if _is_container(original):
            cached = self._identity_cache.get(id(original))
            if cached is not None and cached[0] is original:
                return cached[1]
        encoded = self._encode_original_node(original)
        # Hash the lossless Merkle node, not the repeatedly expanded logical
        # subtree.  Child refs already commit to their complete contents, so
        # this remains content-addressed while avoiding O(depth * bytes).
        canonical = _canonical_safe_bytes(encoded)
        ref = _REF_PREFIX + hashlib.sha256(canonical).hexdigest()
        if ref not in self._entries:
            self._entries[ref] = _store_bytes(encoded)
        if _is_container(original):
            self._identity_cache[id(original)] = (original, ref)
        return ref

    def _intern_safe(self, safe: Any) -> str:
        encoded = self._encode_node(safe)
        canonical = _canonical_safe_bytes(encoded)
        ref = _REF_PREFIX + hashlib.sha256(canonical).hexdigest()
        if ref not in self._entries:
            self._entries[ref] = _store_bytes(encoded)
        return ref

    def intern(self, value: Any) -> str:
        """Intern one logical JSON value and return its full SHA-256 ref."""

        return self._intern_original(value)

    def digest(self) -> str:
        return _mapping_content_digest(self._entries)

    def serialized_size(self) -> int:
        return len(serialized_json_bytes(self.entries))


def _store_argument(
    store: ContentAddressedStore | Mapping[str, Any] | None,
) -> tuple[ContentAddressedStore, MutableMapping[str, Any] | None, bool]:
    if isinstance(store, ContentAddressedStore):
        return store, None, False
    if store is None:
        return ContentAddressedStore(), None, True
    if not isinstance(store, Mapping):
        raise TypeError("store must be a ContentAddressedStore or mapping")
    # A mutable mapping is synchronized after normalization for callers that
    # intentionally supply their own snapshot-local store.
    target = store if isinstance(store, MutableMapping) else None
    return ContentAddressedStore(store), target, False


